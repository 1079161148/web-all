-- =====================================================================
-- 令牌版本号：让"吊销已签发的令牌"成为可能
--
-- 背景（② 会话治理的第一个前置）：
--   本系统的访问令牌是**无状态 JWT**，服务端不存会话 —— 好处是水平扩容
--   无需会话粘滞，代价是**签发之后无法撤回**：改密码、停用账号、
--   管理员强制下线，旧令牌在有效期内（默认 30 分钟）依然可用。
--
-- 为什么版本号放在**数据库**而不是只放 Redis：
--   吊销能力必须是**durable**（持久可信）的。若只存 Redis，
--   一次 Redis 重启/清库就会把所有吊销记录一起抹掉 ——
--   被停用账号的旧令牌会重新生效，而这属于"安全机制静默失效"，
--   比服务不可用严重得多。
--   放在库里的代价只有一列，换来的是"Redis 丢了，吊销依然成立"。
--
-- 为什么是"版本号"而不是"黑名单列表"：
--   黑名单要逐个记录被吊销的令牌（jti），条目随登录次数增长，且要设 TTL 兜底；
--   版本号只是一个<b>单调递增的整数</b>：令牌里带上签发时的版本，
--   与当前版本不一致即失效。一次 UPDATE 吊销该用户的<b>全部</b>令牌，
--   存储量恒定为 1 行，且天然支持"多实例一致"（大家都在读同一行）。
--
-- 与 Redis 会话注册表的分工（见 SessionRegistryPort）：
--   · 版本号（本列）：**粗粒度、持久**——改密/停用/强退用"提升版本号"表达
--   · 会话注册表（Redis）：**细粒度、易失**——注销单个设备、在线会话列表
--   Redis 不可用时会降级为"只校验版本号"，因此上面那些操作仍然生效。
--
-- 兼容性：默认 0，存量令牌的版本也是 0，因此本迁移**不会**让在线用户被踢下线。
-- 幂等性：MySQL 不支持 ADD COLUMN IF NOT EXISTS，而 Flyway 保证本文件只执行一次。
-- =====================================================================

ALTER TABLE `iam_user`
    ADD COLUMN `token_version` BIGINT NOT NULL DEFAULT 0
        COMMENT '令牌版本号：提升即吊销该用户已签发的全部令牌（改密/停用/强制下线）';
