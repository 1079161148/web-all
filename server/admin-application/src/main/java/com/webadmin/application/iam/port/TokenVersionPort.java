package com.webadmin.application.iam.port;

/**
 * 令牌版本号读取与缓存失效。
 *
 * <h3>为什么只有"读"和"失效"，没有"写"</h3>
 * 版本号是 {@code User} 聚合的状态：提升它必须走
 * {@code User.bumpTokenVersion()} + {@code userRepository.save(user)} ——
 * 否则就成了"绕过聚合直接改库"，聚合内的不变量（如"停用必须同时提升版本号"）
 * 会失去唯一的判定入口。
 *
 * <p>因此本端口只负责两件基础设施的事：
 * <ul>
 *   <li>{@link #current} —— 给鉴权路径读"当前版本号"（带缓存）</li>
 *   <li>{@link #evict} —— 聚合保存后清掉缓存（与权限缓存同一套路子）</li>
 * </ul>
 *
 * <h3>读取为什么必须有缓存，以及缓存失效时的降级</h3>
 * 本方法在<b>每个请求</b>上都会被调用（除非会话注册表已经给出了判定）。
 * 直接查库会让鉴权路径重新背上 IO；因此实现是"Redis 缓存 + 回源数据库"。
 *
 * <p>但这里有一个与权限缓存不同的地方：<b>本读取是安全判定的一环</b>。
 * 因此当 Redis 不可用时，实现<b>不能</b>简单地"返回 0 放行" ——
 * 那样等于"Redis 一挂，所有吊销失效"。正确做法是回源数据库，
 * 并用<b>进程内短 TTL 缓存</b>兜住"Redis 挂掉时每个请求都查库"的连接池压力
 * （授权路径打满连接池会让整个系统不可用，比鉴权变慢严重得多）。
 */
public interface TokenVersionPort {

    /**
     * 读取用户当前的令牌版本号。
     *
     * @return 版本号；<b>查不到用户时返回 -1</b>（而非 0）——
     *         调用方据此可判定"用户已被删除"，与"版本号就是 0"区分开。
     *         返回 0 会让一个已被删除的用户在其令牌过期前继续通过校验。
     */
    long current(long tenantId, long userId);

    /** 失效缓存（用户保存后调用）。 */
    void evict(long tenantId, long userId);

    /**
     * 提升<b>某租户全部用户</b>的令牌版本号（暂停 / 过期 / 关闭租户时调用）。
     *
     * <p>这是"租户级强制下线"的实现点：一次批量更新就让该租户所有在线令牌失效，
     * 且持久生效。实现是<b>批量管理动作</b>，直接走 SQL 而不是逐个加载聚合 ——
     * 与 {@code DeptWritePort.rebaseSubtree} 同一取舍：聚合不适合" affecting N 行"的
     * 管理操作，逐个加载再保存在大租户上是灾难。
     *
     * <p>⚠️ 实现会同时清掉这些用户的版本号缓存（不清的话，缓存的旧版本
     * 会让吊销在缓存 TTL 内不生效）。本方法<b>允许抛出异常</b>：
     * 调用方是事件处理器（Modulith 事务性 Outbox，失败可重试），
     * 抛出让它重试比静默失败（吊销丢失）安全得多 —— 与单用户的 fail-soft 相反，
     * 因为这里的失败意味着"整个租户的强制下线没有发生"。
     *
     * @return 受影响的用户数
     */
    long bumpAllForTenant(long tenantId);

    /** 失效某租户全部用户的版本号缓存。 */
    void evictTenant(long tenantId);
}
