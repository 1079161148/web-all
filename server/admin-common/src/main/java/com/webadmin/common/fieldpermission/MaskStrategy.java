package com.webadmin.common.fieldpermission;

/**
 * 脱敏策略。
 *
 * <h3>为什么每种策略都保留"可识别性"</h3>
 * 脱敏的目标不是"让人完全看不到"，而是<b>在可用性与隐私之间取平衡</b>：
 * <ul>
 *   <li>客服需要看到 {@code 138****8888} 才能和客户核对"尾号 8888 的那个号码"</li>
 *   <li>若全部打成 {@code ***}，业务就没法用了，实际结果往往是有人偷偷申请了完整权限</li>
 * </ul>
 * 因此每条策略都刻意保留头尾若干位。<b>过度脱敏会把人推回到"要求完整权限"的路上，
 * 反而降低整体安全性。</b>
 *
 * <h3>关于 Unicode 与长度</h3>
 * 所有实现都按 <b>Code Point</b> 而非 {@code char} 处理，否则遇到 emoji
 * 或生僻字（代理对）时会截断出乱码。<b>这是一个看起来无害、实际很容易出错的细节。</b>
 */
public enum MaskStrategy {

    /** 不脱敏。仅用于配合 {@code visibleFor} / {@code hiddenFor} 做纯显隐控制。 */
    NONE,

    /** 手机号：{@code 138****8888}（保留前 3 后 4）。 */
    PHONE,

    /** 身份证：{@code 110101********1234}（保留前 6 后 4）。 */
    ID_CARD,

    /** 银行卡：{@code 6222 **** **** 1234}（保留前 4 后 4）。 */
    BANK_CARD,

    /** 邮箱：{@code a***@example.com}（保留首字符与完整域名）。 */
    EMAIL,

    /** 姓名：{@code 张**}（保留姓氏）。复姓场景无法自动识别，属已知限制。 */
    NAME,

    /**
     * 通用敏感串：保留前 1/4 与后 1/4，中间以 {@code *} 填充。
     *
     * <p>长度不足 4 时全部打码 —— 短串的部分保留等于没脱敏
     * （比如 3 位保留 1 位就泄露了 1/3 的信息）。
     */
    SENSITIVE,
    ;
}
